package com.ksiracare.backend.dto.request;

import com.ksiracare.backend.enums.Language;
import com.ksiracare.backend.validation.ValidPassword;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.Set;

/**
 * "Add an Aapta": the admin sets up their login and shares it with them.
 *
 * @param email     their login; must not belong to another aapta
 * @param languages ISO 639-1 codes, e.g. ["en", "hi"] — see GET /admin/languages
 * @param password  the first password, typed or generated by the admin; the aapta can change it
 */
public record CreateAaptaRequestDto(
        @NotBlank(message = "First name is required") @Size(max = 100) String firstName,
        @Size(max = 100) String middleName,
        @NotBlank(message = "Last name is required") @Size(max = 100) String lastName,
        @NotBlank(message = "Email is required") @Email(message = "Invalid email format") @Size(max = 255) String email,
        @NotEmpty(message = "Choose at least one language") Set<@NotNull Language> languages,
        @ValidPassword String password
) {
}
